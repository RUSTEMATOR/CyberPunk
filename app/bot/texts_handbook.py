def topic(key: str) -> tuple[str, str, str] | None:
    return next((t for t in TOPICS if t[0] == key), None)


def handbook_page(key: str, balance: BalanceModel) -> str:
    t = topic(key)
    if t is None:
        return ""
    def tier(x) -> str:  # noqa: ANN001
        parts = ([f"проверки {x.checks:+d}"] if x.checks else []) + ([f"опыт {x.xp_pct:+d}%"] if x.xp_pct else []) + \
            ([f"ОД {x.ap_week:+d} в неделю"] if x.ap_week else [])
        return f"• {x.name} (от {x.min}): " + (", ".join(parts).replace("-", "−") if parts else "без бонусов и штрафов")

    tiers = "\n".join(tier(x) for x in balance.healing.mood_tiers)
    grades = balance.economy.immuno.grades
    return t[2].format(
        ap=balance.time.ap_per_week * balance.time.weeks_per_press,
        tick=f"{balance.time.global_tick_hour:02d}",
        collector=balance.death.collector_kill_weeks,
        immuno_from=grades[0].from_load if grades else 12,
        tiers=tiers,
        addict=balance.economy.drugs.addiction_threshold,
        switch=f"{balance.paths.switch_price:,}".replace(",", " "),
        jail_min=balance.jail.min_weeks, jail_max=balance.jail.max_weeks,
        old_age=balance.death.old_age_start,
    )
