def dumps(payload: Mapping[str, Any]) -> str:
    return json.dumps(payload, ensure_ascii=False, default=str, separators=(", ", ": "))


def user_message(kind: str, payload: Mapping[str, Any], **fmt: Any) -> str:
    """Instruction of the kind and the JSON payload (PLAN 8.2)."""
    return f"ЗАДАНИЕ ({kind}): {instruction(kind, **fmt)}\n\nDATA:\n{dumps(payload)}"


