def _danger_word(level: int) -> str:
    return DANGER_WORDS.get(level, DANGER_WORDS[3])


def lore_signature(content: Content, year: int) -> tuple[Any, ...]:
    """What the lore block depends on: the era and which records exist in the year."""
    era = content.era_for_year(year)
    return (
        id(content), era.key,
        tuple(sorted(content.available("districts", year))), tuple(sorted(content.available("gangs", year))),
        tuple(sorted(content.available("fixers", year))), tuple(sorted(content.available("corps", year))),
    )


_lore_cache: dict[tuple[Any, ...], str] = {}


def lore_block(content: Content, year: int) -> str:
    """The cached system block for this world year (rules, style, terms, the world of the era)."""
    sig = lore_signature(content, year)
    cached = _lore_cache.get(sig)
    if cached is not None:
        return cached
    era = content.era_for_year(year)
    # owner request 25.10: the cities of the world stay out of the Night City lore block (they would bloat the cache)
    districts = {k: v for k, v in content.available("districts", year).items() if v.city == "nc"}
    fixers = {k: v for k, v in content.available("fixers", year).items() if any(d in districts for d in v.districts)}
    gangs = {k: v for k, v in content.available("gangs", year).items() if not v.fights_as}
    corps = content.available("corps", year)
    out: list[str] = [RULES, "", "МИР СЕЙЧАС", f"Эпоха «{era.name}» ({era.from_year} - {era.to_year}). {era.brief}",
                      f"Тон новостей: {era.news_tone}.", "", "РАЙОНЫ"]
    for key, d in districts.items():
        gang_names = [gangs[g].name for g in d.gangs if g in gangs]
        corp_names = [corps[c].name for c in d.corps if c in corps]
        fx = fixers.get(d.fixer)
        bits = [f"{d.name}: {d.description}", f"Опасность: {_danger_word(d.danger)}."]
        if fx is not None:
            bits.append(f"Фиксер: {fx.name}.")
        if gang_names:
            bits.append("Банды: " + ", ".join(gang_names) + ".")
        if corp_names:
            bits.append("Корпорации: " + ", ".join(corp_names) + ".")
        if d.places:
            bits.append("Места: " + ", ".join(d.places) + ".")
        out.append(" ".join(bits))
    out += ["", "ФИКСЕРЫ (как говорят)"]
    for f in fixers.values():
        extra = " Легендарная, берёт только известных." if f.legendary else ""
        out.append(f"{f.name}: {f.description} Голос: {f.voice}.{extra}")
    out += ["", "БАНДЫ"]
    for g in gangs.values():
        out.append(f"{g.name}: {g.description} Стиль: {g.style}.")
    out += ["", "КОРПОРАЦИИ И СЛУЖБЫ"]
    for c in corps.values():
        out.append(f"{c.name}: {c.description}")
    # owner report 26.10 «в 2019 году не должно быть Kang Tao»: who does not exist in this year, by name
    absent = [v.name for k, v in content.corps.items() if k not in corps] + \
        [v.name for k, v in content.gangs.items() if k not in gangs and not v.fights_as]
    if absent:
        out += ["", f"В ЭТОМ ГОДУ ИХ ЕЩЁ НЕТ (или уже нет): {', '.join(absent)}. Не упоминай их ни в каком виде."]
    out += ["", "СЛЕНГ", SLANG]
    text = "\n".join(out)
    if len(_lore_cache) > 64:
        _lore_cache.clear()
    _lore_cache[sig] = text
    return text


def system_blocks(content: Content, year: int, digest: str = "") -> list[dict[str, Any]]:
    """The system parameter: the lore block, then the history digest when there is one. Both are cached."""
    blocks: list[dict[str, Any]] = [
        {"type": "text", "text": lore_block(content, year), "cache_control": dict(CACHE_CONTROL)},
    ]
    if digest.strip():
        blocks.append({
            "type": "text", "text": "ИСТОРИЯ МИРА (сжатая, канон и события игроков). Не противоречь ей.\n" + digest.strip(),
            "cache_control": dict(CACHE_CONTROL),
        })
    return blocks


